namespace PoolOfRadianceTrainer.Game;

/// <summary>
/// Per-area wall/door/floor grids for every mapped Pool of Radiance location, transcribed from the
/// game&apos;s own level geometry (<c>GEO1..8.DAX</c> in the POOLRAD folder) rather than from a guide,
/// so the walls the schematic draws are the walls the game actually has.
///
/// <para><b>How the game stores a level.</b> A <c>.DAX</c> file is a container: a
/// <c>UInt16</c> header length, then one 9-byte entry per block (<c>id</c>, <c>UInt32</c> offset,
/// <c>UInt16</c> unpacked size, <c>UInt16</c> packed size), then the packed block data. Blocks are
/// PackBits-style RLE: a lead byte &lt; 0x80 means "copy the next n+1 bytes verbatim", &gt;= 0x80
/// means "repeat the next byte 256-n times". Every GEO block unpacks to 1026 bytes: a 2-byte length
/// (0x0400) then four 256-byte planes, each a 16x16 grid of one byte per square:</para>
/// <list type="bullet">
///   <item>plane 0 - high nibble = north wall index, low nibble = east wall index</item>
///   <item>plane 1 - high nibble = south wall index, low nibble = west wall index</item>
///   <item>plane 2 - per-square backdrop/interior id (not used here)</item>
///   <item>plane 3 - two bits per direction (N=0-1, E=2-3, S=4-5, W=6-7); non-zero = the edge can be
///         walked through, i.e. a door, archway or illusory wall</item>
/// </list>
/// <para>A wall index of 0 means no wall. Shared edges are stored on both squares and agree ~91% of
/// the time; the ~9% that disagree are genuine one-sided walls, so each edge below merges the two
/// sides. An edge that is walkable but whose wall index is also used as a solid wall elsewhere in the
/// same level looks like a wall yet can be walked through - an illusory/secret door, written
/// <c>~</c>. Squares the party can never reach (sealed, or cut off from the main walkable region)
/// are written <c>##</c>; in New Phlan those east of the sea wall are the harbour and are written
/// <c>~~</c> (water), which lines up cell-for-cell with the water on the clue book&apos;s own map.</para>
///
/// <para><b>Which block is which area</b> was established by rendering all 29 GEO blocks and matching
/// them against the printed maps in the bundled clue book (and, for the Slums, against a live memory
/// dump of the running game, which holds the decoded block verbatim). The match is automated: the
/// page scan is thresholded along each grid line to give the same wall/no-wall grid the decoder
/// produces, and the two are scored by Matthews correlation over interior edges. Every block is
/// named; the margin over the runner-up is what settles each one, since the clue book overlays
/// glyphs the game has no notion of (tombstones, swamp, trees) that no decoded block can match.
/// See <c>docs/reverse-engineering.md</c> §7a for the score table and for the two labels
/// (InnerTowerLower and PyramidLevel3) that rest on an assignment argument rather than on a
/// decisive score of their own.</para>
/// </summary>
