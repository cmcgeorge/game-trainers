namespace CurseOfTheAzureBondsTrainer.Game;

/// <summary>
/// Per-area wall/door/floor grids for every mapped Curse of the Azure Bonds level, decoded from the
/// game's own level geometry (<c>GEO2..6.DAX</c> in the CURSE folder) rather than transcribed from a
/// guide, so the walls the schematic draws are the walls the game actually has.
///
/// <para><b>How the game stores a level.</b> A <c>.DAX</c> file is a container: a
/// <c>UInt16</c> header length, then one 9-byte entry per block (<c>id</c>, <c>UInt32</c> offset,
/// <c>UInt16</c> unpacked size, <c>UInt16</c> packed size), then the packed block data. Blocks are
/// PackBits-style RLE: a lead byte &lt; 0x80 means "copy the next n+1 bytes verbatim", &gt;= 0x80
/// means "repeat the next byte 256-n times". Every GEO block unpacks to 1026 bytes: a 2-byte length
/// (0x0400) then four 256-byte planes, each a 16x16 grid of one byte per square:</para>
/// <list type="bullet">
///   <item>plane 0 - high nibble = north wall index, low nibble = east wall index</item>
///   <item>plane 1 - high nibble = south wall index, low nibble = west wall index</item>
///   <item>plane 2 - per-square backdrop/interior id (not used here)</item>
///   <item>plane 3 - two bits per direction (N=0-1, E=2-3, S=4-5, W=6-7); non-zero = the edge can be
///         walked through, i.e. a door, archway or illusory wall</item>
/// </list>
/// <para>A wall index of 0 means no wall. Shared edges are stored on both squares, so each edge below
/// merges the two sides. An edge that is walkable but whose wall index is also used as a solid wall
/// elsewhere in the same level looks like a wall yet can be walked through - an illusory/secret door,
/// written <c>~</c>; an ordinary passable edge is written <c>+</c>. Squares the party can never reach
/// (sealed, or cut off from the level's main walkable region) are written <c>##</c>.</para>
///
/// <para><b>Which block belongs to which area.</b> Unlike the sister trainer, this one has no clue
/// book to match printed maps against - Curse's Adventurer's Journal is not part of the install, and
/// the bundled <c>curseazure.pdf</c> is the rule book, which prints no maps. What the install does
/// carry is each module's <b>monster roster</b> (<c>MON&lt;n&gt;CHA.DAX</c>, one full 422-byte record
/// per creature), and those name the areas outright: module 2 fights bar patrons, royal guards, Fire
/// Knives and sewer otyughs (Tilverton), module 3 fights Mogion, vegepygmies and a Bit o' Moander
/// (Yulash and the Temple of Moander), module 4 the Zhentilar (Zhentil Keep), module 5 dark elves
/// with Dracandros and Akabar (Dracandros's stronghold) and module 6 ends at Tyranthraxus (Myth
/// Drannor). So the <b>module</b> each map belongs to is established; the level names <i>within</i>
/// a module are descriptive labels, not decoded facts, and the block id each one came from is kept
/// in its comment so nothing is lost if a label is wrong. The <b>geometry itself is exact</b> either
/// way, and the Maps tab identifies which one you are standing on by matching the level the game has
/// resident - see <c>Memory/MapLocator.cs</c> - so a mislabelled name never mislocates the party.
/// See <c>docs/reverse-engineering.md</c> §7a.</para>
/// </summary>
