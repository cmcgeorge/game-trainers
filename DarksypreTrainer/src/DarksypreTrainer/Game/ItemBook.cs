namespace DarksypreTrainer.Game;

/// <summary>One object from the game's own <c>OBJ.DAT</c> table, with its table index.</summary>
public sealed record ItemEntry(int Id, string Name)
{
    /// <summary>Coarse grouping derived from the object's own name, for reading the grid.</summary>
    public string Category => Categorize(Name);

    private static string Categorize(string name)
    {
        string n = name.ToLowerInvariant();
        if (n.EndsWith(" rune")) return "Rune";
        if (n.EndsWith(" scroll") || n.StartsWith("scroll of") || n == "spellbook") return "Magic";
        if (n.EndsWith(" potion") || n == "ambrosia" || n == "water") return "Potion";
        if (n.EndsWith(" key") || n.EndsWith(" token")) return "Key";
        if (n.EndsWith(" shield") || n.EndsWith("buckler") || n.EndsWith("warboard")) return "Shield";
        if (n.EndsWith(" helm") || n.EndsWith(" coif")) return "Helm";
        if (n.EndsWith(" sphere")) return "Sphere";
        if (n.StartsWith("amulet")) return "Amulet";
        return "Other";
    }
}

