/// <summary>
/// The wall layout of all 55 Might &amp; Magic 1 mazes, so the drawn-map tab shows every area of
/// the game whether or not the player has pointed the trainer at their own
/// <c>Mazedata.dta</c>. Loading that file still takes precedence: it carries the exact bytes,
/// which is what the live current-map fingerprint needs (see <see cref="MazeData"/>).
///
/// <para><b>Where this comes from.</b> Transcribed from <c>docs/maze-atlas.md</c>, this
/// project's own decode of <c>Mazedata.dta</c> — the same two-plane format
/// <see cref="MazeMap"/> reads. Every record here re-renders to that document byte for byte.
/// What an edge <em>does</em> (plane 2) survives the transcription exactly; the wall
/// <em>graphic</em> (plane 1) survives only as drawn-or-not, which is all the renderer asks
/// of it. A shared edge is recorded once and given to both cells, so the roughly 1.6% of
/// interior edges the game records differently from each side lose the quieter of the two —
/// they are one-sided doors, and the atlas already drew them as one edge.</para>
///
/// <para><b>Grid format.</b> Each map is 33 lines of 33 characters, drawn north-up: line
/// <c>2r</c> holds the horizontal edges above square row <c>r</c> (glyph at index
/// <c>2x + 1</c>, <c>'+'</c> on the corners) and line <c>2r + 1</c> the vertical edges of that
/// row (glyph at index <c>2x</c>, for x = 0..16). Row 0 is y = 15, the map's north edge.
/// Glyphs: <c>'#'</c> blocked, <c>'D'</c> door, <c>'S'</c> special passable edge (secret /
/// one-way / trigger), <c>'o'</c> a wall that is drawn but walkable — MM1's illusory
/// passages — and a space for nothing at all.</para>
/// </summary>
