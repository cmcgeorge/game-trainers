namespace BardsTale1Trainer.Game;

/// <summary>
/// Per-square wall, door and barrier grids for all seventeen Bard&apos;s Tale 1 areas, so the Maps
/// tab draws the real mazes instead of an empty counting grid.
///
/// <para><b>Where this comes from.</b> The 1987 DOS release keeps its levels inside
/// <c>BARD.EXE</c>&apos;s own data in a form this project has not decoded, so the grids below were
/// transcribed from <em>The Bard&apos;s Tale Trilogy</em> remaster, which ships each area as a
/// plain-text map asset and reproduces the original sixteen 22x22 dungeon levels and the 30x30
/// Skara Brae street grid. The extraction is the same read the sibling
/// <c>BardsTaleTrilogyTrainer</c> performs at run time on <c>resources.assets</c>; only the wall
/// layout was taken, and it was checked against the level list this trainer already had
/// (Cellars, three Sewers, three Catacombs, three Harkyn&apos;s, Kylearan&apos;s and five
/// Mangar&apos;s), which it matches level for level. The transcription was then verified back
/// against the assets edge for edge — all 30,976 dungeon sides and Skara Brae&apos;s 32 blocked
/// squares, resolved the way the renderer resolves them, with no mismatch.</para>
///
/// <para><b>Caveat.</b> The remaster is a recreation, not the 1987 binary, so a square here and
/// there may differ from the DOS original — and its Skara Brae lists a Bank and a Casino the DOS
/// game does not have. The walls are the part that matters for mapping and they line up with the
/// published Bard&apos;s Tale 1 maps; treat the labelled services as a guide rather than as proof
/// of what the DOS build offers.</para>
///
/// <para><b>Wrap-around.</b> Every dungeon level wraps: step off the north rim and you come back
/// on the south one. The two rims are therefore the same physical edge, so each is written with
/// the <em>merged</em> glyph rather than its own side&apos;s face — otherwise the three seams the
/// game records asymmetrically would draw as a door on one rim and a wall on the other.</para>
///
/// <para><b>Orientation.</b> Row 0 of each array is the map&apos;s <em>north</em> edge and column 0
/// its west edge. Which way the DOS game&apos;s own X/Y bytes run is deliberately not asserted —
/// that is what the two calibration anchors in <c>MapReferenceViewModel</c> establish, and
/// <see cref="MapCalibration"/> copes with an axis that runs the other way.</para>
///
/// <para>See <see cref="MapAscii"/> for the grid format and the full glyph legend.</para>
/// </summary>
